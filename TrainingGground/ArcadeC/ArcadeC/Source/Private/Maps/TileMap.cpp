TileMap::TileMap()
{
    Dirt = TextureManager::LoadTexture("Assets/TestAsset/Dirt_Texture.png");
    Grass = TextureManager::LoadTexture("Assets/TestAsset/Grass_Texture.png");
    Water = TextureManager::LoadTexture("Assets/TestAsset/Water_Texture.png");
    LoadMap(TestMap);

    //TODO this Should be a variable in Game
    SourceRect.x = SourceRect.y = 0;
    SourceRect.w = SourceRect.h = 32;
    DestinationRect.x = DestinationRect.y = 0;
    DestinationRect.w = DestinationRect.h = 32;
}

TileMap::~TileMap()
{
    
}

void TileMap::LoadMap(const int arr[20][25])
{
    for (int i = 0; i < 20; i++)
    {
        for (int j = 0; j < 25; j++)
        {
            map[i][j] = arr[i][j];
        }
    }
}

void TileMap::DrawMap()
{
    int Type = 0;
    for (uint32_t i = 0; i < 20; i++)
    {
        for (uint32_t j = 0; j < 25; j++)
        {
           Type = map[i][j];
            
            DestinationRect.x = static_cast<float>(j * 32);
            DestinationRect.y = static_cast<float>(i * 32);
            
           switch (Type)
           {
           case 0:
               TextureManager::Draw(Dirt, &SourceRect, &DestinationRect);
               break;
           case 1:
               TextureManager::Draw(Grass, &SourceRect, &DestinationRect);
               break;
           case 2:
               TextureManager::Draw(Water, &SourceRect, &DestinationRect);
               break;
           }
        }
    }
}
